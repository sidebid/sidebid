test('accept mode: waits the window, refund after it, then closes and rent returns to the listing key', async () => {
  const w = on(); flagsOn(w, 'readerLive', 'tagListingLive')
  const s = seller(w); const id = tag(w, s, `@sidebidsol 1 ${s.mint.toBase58()} 1m`); await readerStep(w)
  const listing = w.app.prog.acceptPda(tagListingId(id))
  const b = w.conn.wallet(); bid(w, listing, b, 3_000_000n)
  await w.app.indexer.tick()
  const key = w.config.listingKey.publicKey
  w.conn.warp(60); await w.app.keeper.tick()
  assert.equal(chainListing(w, listing).state, 'live', 'window open: nothing')
  assert.equal(w.db.get('SELECT COUNT(*) n FROM tx_intents WHERE kind IN (?,?)', 'refund', 'close').n, 0)
  // The seller moves the tokens: still the window, since they may accept from another account
  w.conn.warp(599); await w.app.keeper.tick()
  assert.equal(chainListing(w, listing).state, 'live')
  const b0 = w.conn.bal(b.publicKey), k0 = w.conn.bal(key)
  w.conn.warp(1); await w.app.keeper.tick()
  assert.equal(chainListing(w, listing).state, 'ghosted')
  assert.equal(w.conn.bal(b.publicKey), b0 + 3_000_000n)
  await w.app.indexer.tick()
  assert.equal((await w.app.listings.one(listing.toBase58())).status, 'Seller ghosted')
  await w.app.keeper.tick()
  assert.equal(w.conn.info(listing), null)
  assert.equal(w.conn.bal(key), k0 + w.conn.svm.minimumBalanceForRentExemption(317n), 'rent came home')
  await w.app.indexer.reconcile()
  assert.notEqual(w.db.get('SELECT closed_at FROM tag_cards WHERE listing=?', listing.toBase58()).closed_at, null, 'budget freed')
})
