const on = (over) => { const w = world(over); flagsOn(w, 'keeperLive'); return w }
async function auction(w, o = {}) {
  const s = seller(w, o), amount = o.amount2 ?? 1_000_000n
  const listing = listingFixture(w, { sellerKp: s.kp, tokenAccount: s.tokenAccount, mint: s.mint, amount, duration: 60n })
  await w.app.indexer.rebuild()
  return { s, listing, amount }
}
const winnerAta = (s, w) => spl.getAssociatedTokenAddressSync(s.mint, w.publicKey)
const sellerBal = (w, s) => w.conn.bal(s.kp.publicKey)

test('the rule, as a table', () => {
  const pk = Keypair.generate().publicKey, seller = Keypair.generate().publicKey, mint = Keypair.generate().publicKey
  const base = { pubkey: pk, seller, mint, amount: 10n, state: 'live', mode: 'bidding', endTime: 100, topBid: 5n, acceptWindowSecs: 600 }
  const good = { mint, owner: seller, amount: 10n, delegate: pk, delegatedAmount: 10n, frozen: false }
  const T = (o, view, now) => decide({ ...base, ...o }, view, now)
  assert.equal(T({}, good, 99), null, 'before the end')
  assert.equal(T({}, good, 100), 'settle', 'at the very end')
  assert.equal(T({}, null, 100), 'refund', 'seller closed the account: a successful read of nothing')
  assert.equal(T({}, undefined, 100), null, 'unread is not gone')
  assert.equal(T({}, { ...good, delegate: null }, 100), 'refund', 'revoked')
  assert.equal(T({}, { ...good, delegate: seller }, 100), 'refund', 'another delegate')
  assert.equal(T({}, { ...good, delegatedAmount: 9n }, 100), 'refund')
  assert.equal(T({}, { ...good, amount: 9n }, 100), 'refund', 'sold some')
  assert.equal(T({}, { ...good, frozen: true }, 100), 'refund')
  assert.equal(T({}, good, 100 + SETTLE_GRACE_SECS), 'settle_or_refund', 'a day late')
  assert.equal(T({ topBid: 0n }, null, 100), 'close')
  assert.equal(T({ topBid: 0n }, good, 100), 'wait_for_seller', 'the contract refuses while the delegate is set')
  assert.equal(T({ topBid: 0n }, undefined, 100), null, 'unread')
  assert.equal(T({ topBid: 0n }, null, 99), null)
  assert.equal(T({ state: 'gone' }, null, 0), 'close'); assert.equal(T({ state: 'ghosted', mode: 'accept' }, null, 0), 'close')
  assert.equal(T({ state: 'gone' }, good, 0), 'wait_for_seller'); assert.equal(T({ state: 'gone' }, { ...good, delegate: null }, 0), 'close')
  assert.equal(T({ state: 'ghosted', mode: 'accept' }, good, 0), 'close', 'accept mode: a hand approval can\'t hold the rent')
  assert.equal(T({ mode: 'fixed', topBid: 0n, endTime: 100 }, good, 100), 'wait_for_seller')
  assert.equal(T({ mode: 'fixed', endTime: 0 }, null, 1e9), null, 'fixed with no expiry'); assert.equal(T({ mode: 'fixed', topBid: 0n, endTime: 100 }, null, 99), null); assert.equal(T({ mode: 'fixed', topBid: 0n, endTime: 100 }, null, 100), 'close')
  assert.equal(T({ mode: 'accept' }, null, 100), null, 'the window is the seller\'s, even with an empty stored account')
  assert.equal(T({ mode: 'accept' }, null, 699), null); assert.equal(T({ mode: 'accept' }, null, 700), 'refund', 'window over')
  assert.equal(T({ mode: 'accept', topBid: 0n }, null, 100), 'close', 'no bids is not ghosted')
})
test('settles on the first tick at the end: tokens to winner, SOL to seller, opens the winner account', async () => {
  const w = on(); const { s, listing, amount } = await auction(w)
  const b = w.conn.wallet(); bid(w, listing, b, 3_000_000n)
  await w.app.indexer.tick()
  const s0 = sellerBal(w, s)
  await w.app.keeper.tick()
  assert.ok(w.conn.info(listing), 'not before the end')
  w.conn.warp(60)
  await w.app.keeper.tick()
  assert.equal(w.conn.info(listing), null, 'settled and closed in the first tick at the end time')
  assert.equal(w.conn.tokenAmount(winnerAta(s, b)), amount)
  assert.ok(sellerBal(w, s) >= s0 + 3_000_000n, 'bid and rent to the seller')
})
