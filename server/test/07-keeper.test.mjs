test('restart in the middle of a settle: same signature resolved on the new process, one settle', async () => {
  const w = on(); const { s, listing } = await auction(w)
  const b = w.conn.wallet(); bid(w, listing, b, 3_000_000n)
  await w.app.indexer.tick(); w.conn.warp(60)
  // Signed and written down, then the process dies inside the send: the network never saw it
  w.conn.inject('send', () => { throw new Error('process died') }, 1)
  await w.app.keeper.tick()
  const row = w.db.get(`SELECT * FROM tx_intents WHERE kind='settle'`)
  assert.equal(row.status, 'signed'); assert.ok(w.conn.info(listing), 'not landed yet')
  const w2 = world({ conn: w.conn, db: w.db, x: w.x, clock: w.clock, keeperKey: w.keeper })
  await w2.app.start()
  assert.equal(w.conn.info(listing), null, 'the same bytes landed during start')
  await w2.app.keeper.tick()
  const rows = w.db.all(`SELECT * FROM tx_intents WHERE kind='settle'`)
  assert.equal(rows.length, 1); assert.equal(rows[0].sig, row.sig); assert.equal(rows[0].status, 'landed')
  assert.equal(w.conn.tokenAmount(winnerAta(s, b)), 1_000_000n)
})
